func TestDiscoverBoundaryAndBoolean(t *testing.T) {
	d := t.TempDir()
	src := []byte("package p\nfunc f(n int, a, b bool) bool { if n > 0 && a { return b }; return false }\n")
	if err := os.WriteFile(filepath.Join(d, "p.go"), src, 0o644); err != nil {
		t.Fatal(err)
	}
	ms, err := Discover(d, []string{"p.go"}, Options{Operators: map[string]bool{"boundary": true, "boolean": true}})
	if err != nil {
		t.Fatal(err)
	}
	if len(ms) < 4 {
		t.Fatalf("expected at least 4 mutants, got %d: %#v", len(ms), ms)
	}
	for _, m := range ms {
		if m.Diff == "" || m.Suggestion == "" {
			t.Fatalf("incomplete mutant: %#v", m)
		}
	}
}

