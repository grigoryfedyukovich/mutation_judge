package frontend

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestDiscoverBoundaryAndBoolean(t *testing.T) {
	d := t.TempDir()
	src := []byte("package p\nfunc f(n int, a, b bool) bool { if n > 0 && a { return b }; return false }\n")
	if err := os.WriteFile(filepath.Join(d, "p.go"), src, 0o644); err != nil {
		t.Fatal(err)
	}
	ms, err := Discover(d, []string{"p.go"}, Options{Operators: map[string]bool{"boundary": true, "boolean": true}})
	if err != nil {
		t.Fatal(err)
	}
	if len(ms) < 4 {
		t.Fatalf("expected at least 4 mutants, got %d: %#v", len(ms), ms)
	}
	for _, m := range ms {
		if m.Diff == "" || m.Suggestion == "" {
			t.Fatalf("incomplete mutant: %#v", m)
		}
	}
}

func TestChangedLinesFilter(t *testing.T) {
	d := t.TempDir()
	_ = os.WriteFile(filepath.Join(d, "p.go"), []byte("package p\nfunc f(n int) bool {\n return n > 0\n}\n"), 0o644)
	ms, err := Discover(d, []string{"p.go"}, Options{Operators: map[string]bool{"boundary": true}, ChangedLines: map[string]map[int]bool{"p.go": {2: true}}})
	if err != nil {
		t.Fatal(err)
	}
	if len(ms) != 0 {
		t.Fatalf("expected no mutants, got %d", len(ms))
	}
}

func TestGeneratedFilesRespectOption(t *testing.T) {
	d := t.TempDir()
	src := []byte("// Code generated by test. DO NOT EDIT.\npackage p\nfunc f(n int) bool { return n > 0 }\n")
	if err := os.WriteFile(filepath.Join(d, "generated.go"), src, 0o644); err != nil {
		t.Fatal(err)
	}
	without, err := Discover(d, []string{"generated.go"}, Options{Operators: map[string]bool{"boundary": true}})
	if err != nil {
		t.Fatal(err)
	}
	if len(without) != 0 {
		t.Fatalf("generated file should be excluded, got %d mutants", len(without))
	}
	with, err := Discover(d, []string{"generated.go"}, Options{Operators: map[string]bool{"boundary": true}, IncludeGenerated: true})
	if err != nil {
		t.Fatal(err)
	}
	if len(with) != 1 {
		t.Fatalf("generated file should be included explicitly, got %d mutants", len(with))
	}
}

func TestMultilineDiffHasCorrectHunkCounts(t *testing.T) {
	d := t.TempDir()
	src := []byte("package p\nfunc f(a, b bool) bool {\n\treturn a &&\n\t\tb\n}\n")
	if err := os.WriteFile(filepath.Join(d, "p.go"), src, 0o644); err != nil {
		t.Fatal(err)
	}
	ms, err := Discover(d, []string{"p.go"}, Options{Operators: map[string]bool{"boolean": true}})
	if err != nil {
		t.Fatal(err)
	}
	found := false
	for _, m := range ms {
		if m.RuleID == "MJ-BOOL-DROP-RIGHT" {
			found = true
			if !strings.Contains(m.Diff, "@@ -3,2 +3,1 @@") {
				t.Fatalf("unexpected multiline diff:\n%s", m.Diff)
			}
		}
	}
	if !found {
		t.Fatal("missing boolean deletion mutant")
	}
}

func TestBooleanSuggestionsDescribeDistinguishingAssignments(t *testing.T) {
	d := t.TempDir()
	src := []byte("package p\nfunc and(a, b bool) bool { return a && b }\nfunc or(a, b bool) bool { return a || b }\n")
	if err := os.WriteFile(filepath.Join(d, "p.go"), src, 0o644); err != nil {
		t.Fatal(err)
	}
	ms, err := Discover(d, []string{"p.go"}, Options{Operators: map[string]bool{"boolean": true}})
	if err != nil {
		t.Fatal(err)
	}
	for _, m := range ms {
		switch {
		case m.RuleID == "MJ-BOOL-DROP-RIGHT" && strings.Contains(m.Original, "&&"):
			if !strings.Contains(m.Suggestion, "a is true and b is false") {
				t.Fatalf("unexpected && suggestion: %q", m.Suggestion)
			}
		case m.RuleID == "MJ-BOOL-DROP-RIGHT" && strings.Contains(m.Original, "||"):
			if !strings.Contains(m.Suggestion, "a is false and b is true") {
				t.Fatalf("unexpected || suggestion: %q", m.Suggestion)
			}
		}
	}
}
