package frontend

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/example/mutation-judge/internal/model"
)

func discoverBoolDir(t *testing.T, files map[string]string, list []string) []model.Mutation {
	t.Helper()
	d := t.TempDir()
	for name, src := range files {
		path := filepath.Join(d, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	ms, err := Discover(d, list, Options{Operators: map[string]bool{"boolean": true}})
	if err != nil {
		t.Fatal(err)
	}
	return ms
}

func boolLiterals(ms []model.Mutation) []model.Mutation {
	var out []model.Mutation
	for _, m := range ms {
		if m.RuleID == "MJ-BOOL-LITERAL" {
			out = append(out, m)
		}
	}
	return out
}

// The audit fixture: generated.go is excluded from mutation, but its
// package-level true/false still shadow the predeclared constants. The
// initializer looks like a dead store and used to be marked EQUIVALENT
// without being executed, even though flipping it changes float32 to
// float64 and the overwritten value rounds differently.
func TestShadowedBoolAcrossFilesIsNotABooleanLiteral(t *testing.T) {
	ms := discoverBoolDir(t, map[string]string{
		"generated.go": "// Code generated by audit fixture; DO NOT EDIT.\npackage shadowed\nvar true float32\nvar false float64\n",
		"value.go": `package shadowed
func Value() float64 {
	v := true
	v = 16777217
	return float64(v)
}
`,
	}, []string{"value.go"})
	for _, m := range boolLiterals(ms) {
		t.Fatalf("shadowed true/false must not be mutated as boolean constants: %#v", m)
	}
}

func TestShadowedBoolInTheSameFunctionIsNotABooleanLiteral(t *testing.T) {
	ms := discoverBoolDir(t, map[string]string{
		"value.go": `package shadowed
func Value() float64 {
	true := float32(0)
	false := float64(0)
	v := true
	v = 16777217
	return float64(v) + false
}
`,
	}, []string{"value.go"})
	for _, m := range boolLiterals(ms) {
		t.Fatalf("locally shadowed true/false must not be boolean literals: %#v", m)
	}
}

func TestPackageShadowOfReplacementBlocksBooleanLiteral(t *testing.T) {
	ms := discoverBoolDir(t, map[string]string{
		"value.go": `package shadowed
var false float64
func Value() bool {
	v := true
	v = true
	return v
}
`,
	}, []string{"value.go"})
	if got := boolLiterals(ms); len(got) != 0 {
		t.Fatalf("flipping true to a shadowed false is not a boolean-constant mutation: %#v", got)
	}
}

func TestExternalTestPackageDoesNotShadowBooleanLiterals(t *testing.T) {
	ms := discoverBoolDir(t, map[string]string{
		"p.go":      "package p\nfunc f() bool { return true }\n",
		"p_test.go": "package p_test\nvar true int\nvar false int\n",
	}, []string{"p.go"})
	lits := boolLiterals(ms)
	if len(lits) != 1 || lits[0].Original != "true" || lits[0].Replacement != "false" {
		t.Fatalf("package p_test must not shadow package p: %#v", lits)
	}
}

func TestInternalTestFileShadowsBooleanLiterals(t *testing.T) {
	ms := discoverBoolDir(t, map[string]string{
		"p.go":      "package p\nfunc f() bool { return true }\n",
		"p_test.go": "package p\nvar true int\nvar false int\n",
	}, []string{"p.go"})
	if got := boolLiterals(ms); len(got) != 0 {
		t.Fatalf("internal test declarations are part of the test compilation: %#v", got)
	}
}

func TestImportNameShadowsBooleanLiteralOnlyInThatFile(t *testing.T) {
	ms := discoverBoolDir(t, map[string]string{
		"a.go": "package p\nimport true \"fmt\"\nfunc f() bool { return false }\n",
		"b.go": "package p\nfunc g() bool { return true }\n",
	}, []string{"a.go", "b.go"})
	lits := boolLiterals(ms)
	if len(lits) != 1 || lits[0].Span.File != "b.go" || lits[0].Original != "true" {
		t.Fatalf("import name true must block only that file: %#v", lits)
	}
}

func TestParameterShadowBlocksBooleanLiteral(t *testing.T) {
	ms := discoverBoolDir(t, map[string]string{
		"p.go": "package p\nfunc f(true int) bool { return false }\n",
	}, []string{"p.go"})
	if got := boolLiterals(ms); len(got) != 0 {
		t.Fatalf("parameter true means the flipped false is not the predeclared constant: %#v", got)
	}
}

func TestShortDeclInitializerStillFlipsPredeclaredFalse(t *testing.T) {
	ms := discoverBoolDir(t, map[string]string{
		"p.go": "package p\nfunc f() bool {\n\ttrue := false\n\treturn true\n}\n",
	}, []string{"p.go"})
	lits := boolLiterals(ms)
	if len(lits) != 1 || lits[0].Original != "false" || lits[0].Replacement != "true" || lits[0].EquivalentReason != "" {
		t.Fatalf("RHS false is still the predeclared constant; the later true is the variable: %#v", lits)
	}
}

func TestNestedShadowDoesNotHideOuterBooleanLiteral(t *testing.T) {
	ms := discoverBoolDir(t, map[string]string{
		"p.go": `package p
func f() bool {
	if true {
		false := 1
		_ = false
	}
	return false
}
`,
	}, []string{"p.go"})
	lits := boolLiterals(ms)
	if len(lits) != 2 {
		t.Fatalf("outer true and false stay predeclared: %#v", lits)
	}
	for _, m := range lits {
		if m.EquivalentReason != "" {
			t.Fatalf("neither outer constant is a dead store: %#v", m)
		}
	}
}

func TestOrdinaryDeadStoreStillEquivalentWithSiblingFile(t *testing.T) {
	ms := discoverBoolDir(t, map[string]string{
		"other.go": "package p\nvar n int\n",
		"p.go": `package p
func f(g func() bool) bool {
	seen := false
	seen = g()
	return seen
}
`,
	}, []string{"p.go"})
	m := boolLiteralMutantAtLine(t, ms, 3)
	if m.EquivalentReason == "" || m.Original != "false" || m.Replacement != "true" {
		t.Fatalf("builtin dead store must stay equivalent: %#v", m)
	}
}
