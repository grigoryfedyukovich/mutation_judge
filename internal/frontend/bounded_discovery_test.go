func boundedSource(n int) string {
	var b strings.Builder
	b.WriteString("package p\n")
	for i := 0; i < n; i++ {
		fmt.Fprintf(&b, "func f%d(x int) bool { return x > %d && x < %d }\n", i, i, i+100)
	}
	return b.String()
}

func writeBoundedSource(t testing.TB, root, name, data string) {
	t.Helper()
	path := filepath.Join(root, name)
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(data), 0644); err != nil {
		t.Fatal(err)
	}
}

func TestR07S4BoundedDiscoveryMatchesFullOrderAndPatches(t *testing.T) {
	root := t.TempDir()
	// Intentionally unsorted filenames and multiple mutations at an offset.
	writeBoundedSource(t, root, "z.go", boundedSource(12))
	writeBoundedSource(t, root, "a.go", boundedSource(15))
	writeBoundedSource(t, root, "sub/m.go", boundedSource(8))
	opts := Options{Operators: map[string]bool{"boundary": true, "boolean": true, "relational": true}}
	files := []string{"z.go", "sub/m.go", "a.go"}
	full, err := Discover(root, files, opts)
	if err != nil {
		t.Fatal(err)
	}
	if len(full) < 50 {
		t.Fatalf("expected substantial discovery set: %d", len(full))
	}
	for _, limit := range []int{0, 1, 2, 7, 33, len(full) - 1, len(full), len(full) + 5} {
		got, count, err := DiscoverLimited(root, files, opts, limit)
		if err != nil {
			t.Fatalf("limit %d: %v", limit, err)
		}
		if count != len(full) {
			t.Fatalf("limit %d: count=%d want %d", limit, count, len(full))
		}
		expectedLen := len(full)
		if limit > 0 && expectedLen > limit {
			expectedLen = limit
		}
		if !reflect.DeepEqual(got, full[:expectedLen]) {
			t.Fatalf("limit %d: selected mutations differ from complete discovery", limit)
		}
		for _, m := range got {
			if m.Diff == "" || m.Description == "" || m.Suggestion == "" {
				t.Fatalf("incomplete retained mutation: %+v", m)
			}
		}
	}
}

func TestR07S4BoundedDiscoveryStillValidatesEverything(t *testing.T) {
	root := t.TempDir()
	writeBoundedSource(t, root, "a.go", boundedSource(10))
	writeBoundedSource(t, root, "z.go", "package p\nfunc bad(")
	opts := Options{Operators: map[string]bool{"boundary": true}}
	if _, _, err := DiscoverLimited(root, []string{"a.go", "z.go"}, opts, 1); err == nil {
		t.Fatal("a syntax error after the selected mutant was hidden")
	}
	if _, _, err := DiscoverLimited(root, []string{"a.go", "a.go"}, opts, 1); err == nil {
		t.Fatal("duplicate IDs after the selected mutant were hidden")
	}
	if _, _, err := DiscoverLimited(root, []string{"a.go"}, opts, -1); err == nil {
		t.Fatal("accepted negative limit")
	}
}

func TestR07S4BoundedDiscoveryHonorsChangedLinesAndGenerated(t *testing.T) {
	root := t.TempDir()
	writeBoundedSource(t, root, "a.go", "// Code generated by tool. DO NOT EDIT.\n"+boundedSource(4))
	writeBoundedSource(t, root, "b.go", boundedSource(3))
	opts := Options{Operators: map[string]bool{"boundary": true}, ChangedLines: map[string]map[int]bool{"b.go": {2: true}}}
	all, err := Discover(root, []string{"a.go", "b.go"}, opts)
	if err != nil {
		t.Fatal(err)
	}
	if len(all) == 0 {
		t.Fatal("no changed-line mutants")
	}
	got, n, err := DiscoverLimited(root, []string{"a.go", "b.go"}, opts, 1)
	if err != nil {
		t.Fatal(err)
	}
	if n != len(all) || !reflect.DeepEqual(got, all[:1]) {
		t.Fatalf("bounded changed-line discovery differs: count=%d, got=%+v, all=%+v", n, got, all)
	}
}

func BenchmarkR07S4Discovery(b *testing.B) {
	root := b.TempDir()
	for i := 0; i < 25; i++ {
		writeBoundedSource(b, root, fmt.Sprintf("p%03d.go", i), boundedSource(60))
	}
	files := make([]string, 25)
	for i := range files {
		files[i] = fmt.Sprintf("p%03d.go", i)
	}
	opts := Options{Operators: map[string]bool{"boundary": true, "boolean": true}}
	for _, limit := range []int{0, 20} {
		name := "unlimited"
		if limit > 0 {
			name = "max20"
		}
		b.Run(name, func(b *testing.B) {
			b.ReportAllocs()
			for i := 0; i < b.N; i++ {
				var mutants []model.Mutation
				var err error
				if limit == 0 {
					mutants, err = Discover(root, files, opts)
				} else {
					mutants, _, err = DiscoverLimited(root, files, opts, limit)
				}
				if err != nil {
					b.Fatal(err)
				}
				if len(mutants) == 0 {
					b.Fatal("no mutants")
				}
			}
		})
	}
}

// This oracle reproduces the old all-at-once global ordering rather than
// calling DiscoverLimited itself. It catches accidental per-file ordering
// changes when two operators share a source position.
func TestR07S4GlobalSortOracle(t *testing.T) {
	root := t.TempDir()
	files := []string{"z.go", "a.go"}
	for _, f := range files {
		writeBoundedSource(t, root, f, boundedSource(8))
	}
	opts := Options{Operators: map[string]bool{"boundary": true, "boolean": true, "relational": true}}
	var old []model.Mutation
	for _, rel := range files {
		data, err := os.ReadFile(filepath.Join(root, rel))
		if err != nil {
			t.Fatal(err)
		}
		ms, err := discoverFile(rel, data, opts)
		if err != nil {
			t.Fatal(err)
		}
		old = append(old, ms...)
	}
	sort.Slice(old, func(i, j int) bool {
		if old[i].Span.File != old[j].Span.File {
			return old[i].Span.File < old[j].Span.File
		}
		if old[i].Span.StartByte != old[j].Span.StartByte {
			return old[i].Span.StartByte < old[j].Span.StartByte
		}
		return old[i].ID < old[j].ID
	})
	got, n, err := DiscoverLimited(root, files, opts, 5)
	if err != nil {
		t.Fatal(err)
	}
	if n != len(old) || !reflect.DeepEqual(got, old[:5]) {
		t.Fatal("bounded discovery does not match original global ordering")
	}
}
